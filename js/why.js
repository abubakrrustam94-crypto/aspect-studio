(function () {
  WHY.forEach(([sel, text], i) => {
    const el = document.querySelector(sel); if (!el) return;
    const wrap = el.parentElement, label = (wrap && wrap.querySelector(':scope > .field-label')) || el.closest('.card').querySelector('.card-title');
    if (!label) return;
    const id = 'why' + i, p = document.createElement('p');
    p.className = 'note why-text'; p.id = id; p.hidden = true; p.textContent = text;
    const b = document.createElement('button');
    b.type = 'button'; b.className = 'why-btn'; b.textContent = '?'; b.setAttribute('aria-expanded', 'false'); b.setAttribute('aria-controls', id);
    b.setAttribute('aria-label', 'Почему так? ' + (label.textContent || '').trim()); b.title = 'Почему так?';
    b.addEventListener('click', () => { p.hidden = !p.hidden; b.setAttribute('aria-expanded', String(!p.hidden)); });
    label.append(b);
    (el.closest('.range-row, .row') || el).after(p);
  });
})();
